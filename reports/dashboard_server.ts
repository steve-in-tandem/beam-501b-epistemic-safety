import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type {
  AdversarialTestCase,
  RolloutEvaluationRecord,
} from '../benchmark/schema.ts';
import type { SimulationProfile } from '../harness/beam_client.ts';
import {
  ensureSeedHistoricalRuns,
  loadAllHistoricalRuns,
  runReasoningSweep,
  saveHistoricalRun,
  type HistoricalSweepRun,
} from '../harness/reasoning_sweep.ts';
import { calculateSweepMetrics } from '../harness/verifier/metrics.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT_DIR = join(__dirname, '..');
const SEED_CASES_PATH = join(ROOT_DIR, 'benchmark', 'seed_cases.json');
const SAM_CASES_PATH = join(ROOT_DIR, 'benchmark', 'sam_gov_cases.json');
const DASHBOARD_HTML_PATH = join(__dirname, 'dashboard.html');
const DASHBOARD_DATA_JS_PATH = join(__dirname, 'dashboard_data.js');

export function loadSeedCases(): AdversarialTestCase[] {
  const raw = readFileSync(SEED_CASES_PATH, 'utf8');
  const seedCases = JSON.parse(raw) as AdversarialTestCase[];
  if (existsSync(SAM_CASES_PATH)) {
    const samCases = JSON.parse(
      readFileSync(SAM_CASES_PATH, 'utf8')
    ) as AdversarialTestCase[];
    return [...seedCases, ...samCases];
  }
  return seedCases;
}

/**
 * Generates `reports/dashboard_data.js` containing all historical runs and seed cases
 * so `reports/dashboard.html` works both as a standalone static file (`file://`)
 * and when served via `npm run dashboard`.
 */
export async function syncStaticDashboardData(): Promise<{
  runs: HistoricalSweepRun[];
  seedCases: AdversarialTestCase[];
}> {
  await ensureSeedHistoricalRuns();
  const runs = loadAllHistoricalRuns();
  const seedCases = loadSeedCases();

  const jsPayload = [
    '// Auto-generated by reports/dashboard_server.ts — Do not edit manually',
    `window.__BEAM_DASHBOARD_BOOTSTRAP__ = ${JSON.stringify(
      { runs, seedCases },
      null,
      2
    )};`,
    '',
  ].join('\n');

  writeFileSync(DASHBOARD_DATA_JS_PATH, jsPayload, 'utf8');
  return { runs, seedCases };
}

function sendJson(res: ServerResponse, status: number, data: unknown): void {
  const body = JSON.stringify(data);
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
  });
  res.end(body);
}

function readRequestBody(req: IncomingMessage): Promise<string> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    req.on('data', (chunk: Buffer) => chunks.push(chunk));
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

export async function startDashboardServer(port = 4173): Promise<void> {
  await syncStaticDashboardData();

  let activeSweepProgress = {
    running: false,
    completed: 0,
    total: 40,
    currentCase: '',
    profile: '',
  };

  const server = createServer(async (req, res) => {
    try {
      const url = new URL(req.url ?? '/', `http://localhost:${port}`);

      if (
        req.method === 'GET' &&
        (url.pathname === '/' || url.pathname === '/dashboard.html')
      ) {
        const html = readFileSync(DASHBOARD_HTML_PATH, 'utf8');
        res.writeHead(200, {
          'Content-Type': 'text/html; charset=utf-8',
          'Cache-Control': 'no-store',
        });
        res.end(html);
        return;
      }

      if (req.method === 'GET' && url.pathname === '/dashboard_data.js') {
        const js = readFileSync(DASHBOARD_DATA_JS_PATH, 'utf8');
        res.writeHead(200, {
          'Content-Type': 'application/javascript; charset=utf-8',
          'Cache-Control': 'no-store',
        });
        res.end(js);
        return;
      }

      if (req.method === 'GET' && url.pathname === '/api/runs') {
        const runs = loadAllHistoricalRuns();
        const seedCases = loadSeedCases();
        sendJson(res, 200, { runs, seedCases });
        return;
      }

      if (req.method === 'GET' && url.pathname === '/api/sweep-progress') {
        sendJson(res, 200, activeSweepProgress);
        return;
      }

      if (req.method === 'POST' && url.pathname === '/api/runs') {
        const rawBody = await readRequestBody(req);
        const body = (rawBody ? JSON.parse(rawBody) : {}) as {
          profile?:
            | SimulationProfile
            | 'live'
            | 'sam-dry-run'
            | 'sam-live';
          label?: string;
        };

        const isSam =
          body.profile === 'sam-dry-run' || body.profile === 'sam-live';
        const isLive =
          body.profile === 'live' || body.profile === 'sam-live';
        const profile: SimulationProfile =
          body.profile &&
          body.profile !== 'live' &&
          body.profile !== 'sam-dry-run' &&
          body.profile !== 'sam-live'
            ? body.profile
            : 'baseline';

        const defaultSamLabel = isSam
          ? `SAM.gov Full-Stack (10 Solicitations / 67 Attachments) — ${
              isLive ? 'Live Beam 501B' : 'Dry-Run'
            }`
          : undefined;

        const customLabel = body.label?.trim() || defaultSamLabel;

        activeSweepProgress = {
          running: true,
          completed: 0,
          total: 40,
          currentCase: isSam ? 'SAM-001' : 'CASE-001',
          profile: body.profile ?? 'baseline',
        };

        try {
          const { run } = await runReasoningSweep({
            dryRun: !isLive,
            simulationProfile: profile,
            seedCasesPath: isSam ? SAM_CASES_PATH : SEED_CASES_PATH,
            label: customLabel,
            saveToHistory: true,
            onProgress: (completed, total, caseId) => {
              activeSweepProgress = {
                running: true,
                completed,
                total,
                currentCase: caseId,
                profile: body.profile ?? 'baseline',
              };
            },
          });

          await syncStaticDashboardData();
          sendJson(res, 201, { run, runs: loadAllHistoricalRuns() });
        } finally {
          activeSweepProgress.running = false;
        }
        return;
      }

      if (req.method === 'POST' && url.pathname === '/api/import') {
        const rawBody = await readRequestBody(req);
        const body = JSON.parse(rawBody) as {
          filename?: string;
          content?: string;
          label?: string;
        };

        if (!body.content) {
          sendJson(res, 400, { error: 'Missing file content' });
          return;
        }

        const trimmed = body.content.trim();
        let importedRun: HistoricalSweepRun;

        if (trimmed.startsWith('{') && !trimmed.includes('\n{')) {
          const parsedObj = JSON.parse(trimmed) as Partial<HistoricalSweepRun>;
          if (parsedObj.records && Array.isArray(parsedObj.records)) {
            const summary =
              parsedObj.summary ?? calculateSweepMetrics(parsedObj.records);
            const nowIso = parsedObj.created_at ?? new Date().toISOString();
            importedRun = {
              run_id:
                parsedObj.run_id ??
                `run-import-${Date.now().toString(36)}`,
              label:
                body.label?.trim() ||
                parsedObj.label ||
                `Imported ${body.filename ?? 'run'}`,
              profile: parsedObj.profile ?? 'baseline',
              model_id: 'Beam-1.0-501B-A23B',
              adapter_id: parsedObj.adapter_id ?? null,
              is_dry_run: parsedObj.is_dry_run ?? true,
              created_at: nowIso,
              total_rollouts: summary.total_rollouts,
              overall_sar: summary.overall_sar,
              overall_vcp: summary.overall_vcp,
              overall_car: summary.overall_car,
              overall_mean_reward: summary.overall_mean_reward,
              reasoning_rationalization_delta:
                summary.reasoning_rationalization_delta,
              summary,
              records: parsedObj.records,
            };
          } else {
            throw new Error('Invalid run JSON format');
          }
        } else {
          // Parse JSONL rollout evaluation records
          const records = trimmed
            .split(/\r?\n/)
            .map((line) => line.trim())
            .filter(Boolean)
            .map((line) => JSON.parse(line) as RolloutEvaluationRecord);

          const summary = calculateSweepMetrics(records);
          const nowIso = new Date().toISOString();
          importedRun = {
            run_id: `run-import-${Date.now().toString(36)}`,
            label:
              body.label?.trim() ||
              `Imported ${body.filename ?? 'rollouts.jsonl'}`,
            profile: 'baseline',
            model_id: 'Beam-1.0-501B-A23B',
            adapter_id: null,
            is_dry_run: true,
            created_at: nowIso,
            total_rollouts: summary.total_rollouts,
            overall_sar: summary.overall_sar,
            overall_vcp: summary.overall_vcp,
            overall_car: summary.overall_car,
            overall_mean_reward: summary.overall_mean_reward,
            reasoning_rationalization_delta:
              summary.reasoning_rationalization_delta,
            summary,
            records,
          };
        }

        saveHistoricalRun(importedRun);
        await syncStaticDashboardData();
        sendJson(res, 201, { run: importedRun, runs: loadAllHistoricalRuns() });
        return;
      }

      sendJson(res, 404, { error: 'Not found' });
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      sendJson(res, 500, { error: message });
    }
  });

  server.listen(port, () => {
    console.log(
      `================================================================================`
    );
    console.log(
      `Beam-501B Proof-of-Truth Verification Report Dashboard`
    );
    console.log(`Live URL       : http://localhost:${port}`);
    console.log(`Static HTML    : ${DASHBOARD_HTML_PATH}`);
    console.log(`History Folder : ${join(ROOT_DIR, 'rollouts', 'history')}`);
    console.log(
      `================================================================================`
    );
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--sync-only')) {
    syncStaticDashboardData().then(({ runs }) => {
      console.log(
        `[Dashboard Sync] Synced ${runs.length} historical runs to reports/dashboard_data.js`
      );
    });
  } else {
    const port = Number(process.env.PORT ?? 4173);
    startDashboardServer(port);
  }
}

